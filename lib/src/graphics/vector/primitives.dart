/// A free-form curve object, represented as a list of [VectorPath]s.
///
/// This is the most general primitive: rectangles, circles, and polygons can
/// all be converted to curves via [toCurve].
class VectorCurve extends PrimitiveObject {
  VectorCurve({
    super.parent,
    super.trafo,
    super.style,
    super.fillTrafo,
    super.strokeTrafo,
    List<VectorPath>? paths,
  }) : paths = paths ?? [];

  /// The sub-paths that make up this curve.
  List<VectorPath> paths;

  @override
  bool get isCurve => true;

  @override
  bool get isClosed {
    for (final path in paths) {
      if (path.isClosed) return true;
    }
    return false;
  }

  /// Whether all sub-paths are closed.
  bool get isClosedAll {
    for (final path in paths) {
      if (path.isOpen) return false;
    }
    return true;
  }

  @override
  List<VectorPath> getInitialPaths() => paths;

  @override
  DocumentObject? toCurve() => this;

  @override
  DocumentObject createEmpty() => VectorCurve();

  @override
  void copyFields(DocumentObject target) {
    super.copyFields(target);
    if (target is VectorCurve) {
      target.paths = paths.map((p) => p.copyWith()).toList();
    }
  }

  @override
  String toString() => 'VectorCurve(${paths.length} paths, closed=$isClosed)';
}

