/// A regular polygon or star shape.
///
/// The initial shape is inscribed in a unit circle centered at (0.5, 0.5).
class VectorPolygon extends PrimitiveObject {
  VectorPolygon({
    super.parent,
    super.trafo,
    super.style,
    super.fillTrafo,
    super.strokeTrafo,
    this.cornersNum = kDefaultPolygonNum,
    this.angle1 = 0.0,
    this.angle2 = 0.0,
    this.coef1 = 1.0,
    this.coef2 = 1.0,
    List<double>? initialTrafo,
  }) : initialTrafo = initialTrafo ?? List.of(kNormalTrafo);

  /// Number of corners.
  int cornersNum;

  /// Angle offset for corners (radians).
  double angle1;

  /// Angle offset for midpoints (radians).
  double angle2;

  /// Radius coefficient for corners (1.0 = on the circle).
  double coef1;

  /// Radius coefficient for midpoints (1.0 = on the circle; <1 = star).
  double coef2;

  /// Initial transform.
  List<double> initialTrafo;

  @override
  bool get isPolygon => true;

  @override
  bool get isClosed => true;

  double get cornerRadius => 0.5;

  double get midpointRadius => cornerRadius * math.cos(math.pi / cornersNum);

  double getCornerAngle(int index) {
    var val = 2.0 * math.pi / cornersNum * index + math.pi / 2.0;
    if (val > 2.0 * math.pi) val -= 2.0 * math.pi;
    return val;
  }

  double getMidpointAngle(int index) {
    var val = getCornerAngle(index) + math.pi / cornersNum;
    if (val > 2.0 * math.pi) val -= 2.0 * math.pi;
    return val;
  }

  @override
  List<VectorPath> getInitialPaths() {
    return _getPolygonPaths(cornersNum, angle1, angle2, coef1, coef2);
  }

  @override
  DocumentObject createEmpty() => VectorPolygon();

  @override
  void copyFields(DocumentObject target) {
    super.copyFields(target);
    if (target is VectorPolygon) {
      target.cornersNum = cornersNum;
      target.angle1 = angle1;
      target.angle2 = angle2;
      target.coef1 = coef1;
      target.coef2 = coef2;
      target.initialTrafo = List.of(initialTrafo);
    }
  }

  @override
  String toString() =>
      'VectorPolygon($cornersNum corners, coef1=$coef1, coef2=$coef2)';
}

