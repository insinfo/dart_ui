/// A rectangle with optional rounded corners.
///
/// Defined by a start point (lower-left) and width/height. The [corners]
/// list describes rounding level (0.0–1.0) clockwise from lower-left.
class VectorRectangle extends PrimitiveObject {
  VectorRectangle({
    super.parent,
    super.trafo,
    super.style,
    super.fillTrafo,
    super.strokeTrafo,
    this.startX = 0.0,
    this.startY = 0.0,
    this.rectWidth = 1.0,
    this.rectHeight = 1.0,
    List<double>? corners,
  }) : corners = corners ?? List.of(kCorners);

  double startX;
  double startY;
  double rectWidth;
  double rectHeight;

  /// Corner rounding `[lowerLeft, upperLeft, upperRight, lowerRight]`, 0.0–1.0.
  List<double> corners;

  @override
  bool get isRect => true;

  @override
  bool get isClosed => true;

  /// Sets geometry from a `[x, y, w, h]` list.
  void setRect(List<double> rect) {
    startX = rect[0];
    startY = rect[1];
    rectWidth = rect[2];
    rectHeight = rect[3];
  }

  /// Returns geometry as `[x, y, w, h]`.
  List<double> getRect() => [startX, startY, rectWidth, rectHeight];

  @override
  List<VectorPath> getInitialPaths() {
    return _getRectPaths(startX, startY, rectWidth, rectHeight, corners);
  }

  /// The four corner points before rounding.
  List<Offset> get cornerPoints => [
        Offset(startX, startY),
        Offset(startX, startY + rectHeight),
        Offset(startX + rectWidth, startY + rectHeight),
        Offset(startX + rectWidth, startY),
      ];

  @override
  DocumentObject createEmpty() => VectorRectangle();

  @override
  void copyFields(DocumentObject target) {
    super.copyFields(target);
    if (target is VectorRectangle) {
      target.startX = startX;
      target.startY = startY;
      target.rectWidth = rectWidth;
      target.rectHeight = rectHeight;
      target.corners = List.of(corners);
    }
  }

  @override
  String toString() =>
      'VectorRectangle(${startX.toStringAsFixed(1)}, ${startY.toStringAsFixed(1)}, '
      '${rectWidth.toStringAsFixed(1)}×${rectHeight.toStringAsFixed(1)})';
}

