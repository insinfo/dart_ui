/// A single sub-path: a start point, a list of segments, and a closure flag.
class VectorPath {
  VectorPath({
    required this.start,
    List<Object>? points,
    this.closure = PathClosure.opened,
  }) : points = points ?? [];

  /// The starting point of this sub-path.
  Offset start;

  /// Segment points: either [Offset] (line-to) or [CurvePoint] (cubic Bézier).
  List<Object> points;

  /// Whether this sub-path is closed.
  PathClosure closure;

  bool get isOpen => closure == PathClosure.opened;
  bool get isClosed => closure == PathClosure.closed;

  VectorPath copyWith({
    Offset? start,
    List<Object>? points,
    PathClosure? closure,
  }) =>
      VectorPath(
        start: start ?? this.start,
        points: points ?? List.of(this.points),
        closure: closure ?? this.closure,
      );

  @override
  String toString() =>
      'VectorPath(start=$start, ${points.length} segments, $closure)';
}

/// A cubic Bézier curve point with two control handles and a node type.
class CurvePoint {
  const CurvePoint(this.control1, this.control2, this.endpoint,
      [this.nodeType = NodeType.cusp]);

  final Offset control1;
  final Offset control2;
  final Offset endpoint;
  final NodeType nodeType;

  CurvePoint copyWith({
    Offset? control1,
    Offset? control2,
    Offset? endpoint,
    NodeType? nodeType,
  }) =>
      CurvePoint(
        control1 ?? this.control1,
        control2 ?? this.control2,
        endpoint ?? this.endpoint,
        nodeType ?? this.nodeType,
      );

  @override
  String toString() =>
      'CurvePoint($control1 → $control2 → $endpoint, $nodeType)';
}

