/// Base class for graphics primitives that have their own geometry.
///
/// Each primitive stores a [trafo] (affine transform) and a [style] (fill +
/// stroke). The geometry is generated by [getInitialPaths] and cached in
/// [cachePaths] after applying the transform.
abstract class PrimitiveObject extends SelectableObject {
  PrimitiveObject({
    super.parent,
    super.trafo,
    super.style,
    List<double>? fillTrafo,
    List<double>? strokeTrafo,
  })  : fillTrafo = fillTrafo ?? [],
        strokeTrafo = strokeTrafo ?? [];

  /// Transform applied to the fill pattern/gradient.
  List<double> fillTrafo;

  /// Transform applied to the stroke (for scalable strokes).
  List<double> strokeTrafo;

  /// Cached paths after generation (pre-transform).
  List<VectorPath>? cachePaths;

  /// Cached line width after stroke transform.
  double? cacheLineWidth;

  @override
  bool get isPrimitive => true;

  /// Generates the raw geometry paths in local coordinates (before [trafo]).
  List<VectorPath> getInitialPaths();

  /// Whether this shape is geometrically closed.
  bool get isClosed => false;

  @override
  void update() {
    cachePaths = getInitialPaths();
    updateStroke();
    updateBbox();
  }

  void updateStroke() {
    if (style.stroke.isNone) return;
    if (strokeTrafo.isEmpty || !style.stroke.scalableStroke) {
      cacheLineWidth = style.stroke.width;
    } else {
      // Compute the effective line width under the stroke transform.
      final p0 = applyTrafoToPoint(Offset.zero, strokeTrafo);
      final p1 = applyTrafoToPoint(const Offset(1, 0), strokeTrafo);
      final coef = pointsDistance(p0, p1);
      cacheLineWidth = style.stroke.width * coef;
    }
  }

  @override
  void updateBbox() {
    if (cachePaths == null || cachePaths!.isEmpty) {
      cacheBbox = Rect.zero;
      return;
    }
    // Compute bounding box from all path points, transformed.
    double minX = double.infinity;
    double minY = double.infinity;
    double maxX = double.negativeInfinity;
    double maxY = double.negativeInfinity;

    for (final path in cachePaths!) {
      for (final point in _allPoints(path)) {
        final tp = applyTrafoToPoint(point, trafo);
        if (tp.dx < minX) minX = tp.dx;
        if (tp.dy < minY) minY = tp.dy;
        if (tp.dx > maxX) maxX = tp.dx;
        if (tp.dy > maxY) maxY = tp.dy;
      }
    }

    if (minX == double.infinity) {
      cacheBbox = Rect.zero;
    } else {
      // Expand by half stroke width.
      final sw = (cacheLineWidth ?? 0) / 2.0;
      cacheBbox = Rect.fromLTRB(minX - sw, minY - sw, maxX + sw, maxY + sw);
    }
  }

  /// Applies [newTrafo] in document space. See [SelectableObject.applyTrafo]
  /// for why the new transform goes on the *left* of the multiplication.
  @override
  void applyTrafo(List<double> newTrafo) {
    trafo = multiplyTrafo(newTrafo, trafo);
    if (fillTrafo.isNotEmpty) {
      fillTrafo = multiplyTrafo(newTrafo, fillTrafo);
    }
    if (strokeTrafo.isNotEmpty) {
      strokeTrafo = multiplyTrafo(newTrafo, strokeTrafo);
      updateStroke();
    }
    updateBbox();
  }

  @override
  DocumentObject? toCurve() {
    final curve = VectorCurve(
      trafo: List.of(trafo),
      style: style.copyWith(),
      paths: cachePaths
              ?.map((p) => VectorPath(
                    start: p.start,
                    points: List.of(p.points),
                    closure: p.closure,
                  ))
              .toList() ??
          [],
    );
    curve.fillTrafo = List.of(fillTrafo);
    curve.strokeTrafo = List.of(strokeTrafo);
    curve.update();
    return curve;
  }

  @override
  void copyFields(DocumentObject target) {
    super.copyFields(target);
    if (target is PrimitiveObject) {
      target.fillTrafo = List.of(fillTrafo);
      target.strokeTrafo = List.of(strokeTrafo);
      target.cacheLineWidth = cacheLineWidth;
    }
  }

  @override
  void clearColorCache() {
    // Clear any pattern image caches.
  }

  /// Extracts all points from a [VectorPath] for bbox computation.
  static Iterable<Offset> _allPoints(VectorPath path) sync* {
    yield path.start;
    for (final pt in path.points) {
      if (pt is CurvePoint) {
        yield pt.control1;
        yield pt.control2;
        yield pt.endpoint;
      } else if (pt is Offset) {
        yield pt;
      }
    }
  }
}

