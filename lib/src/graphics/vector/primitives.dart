/// The kappa constant for approximating quarter-circles with cubic Béziers.
/// Error is ~0.027% of the radius.
const double _kappa = 0.5522847498;

/// Generates rectangle paths with optional rounded corners.
List<VectorPath> _getRectPaths(
    double x, double y, double w, double h, List<double> corners) {
  final hasRounding = corners.any((c) => c > 0.0);

  if (!hasRounding) {
    // Simple rectangle: 4 line segments, closed.
    return [
      VectorPath(
        start: Offset(x, y),
        points: [
          Offset(x, y + h),
          Offset(x + w, y + h),
          Offset(x + w, y),
        ],
        closure: PathClosure.closed,
      ),
    ];
  }

  // Rounded rectangle: approximate each corner arc with a cubic Bézier.
  final r = math.min(w, h) / 2.0;
  final c0 = corners[0].clamp(0.0, 1.0) * r; // lower-left
  final c1 = corners[1].clamp(0.0, 1.0) * r; // upper-left
  final c2 = corners[2].clamp(0.0, 1.0) * r; // upper-right
  final c3 = corners[3].clamp(0.0, 1.0) * r; // lower-right

  final points = <Object>[];

  // Start at lower-left, after the corner arc
  final start = Offset(x, y + c0);

  // Left edge → upper-left corner
  if (c1 > 0) {
    points.add(Offset(x, y + h - c1));
    points.add(CurvePoint(
      Offset(x, y + h - c1 + c1 * _kappa),
      Offset(x + c1 - c1 * _kappa, y + h),
      Offset(x + c1, y + h),
      NodeType.smooth,
    ));
  } else {
    points.add(Offset(x, y + h));
  }

  // Top edge → upper-right corner
  if (c2 > 0) {
    points.add(Offset(x + w - c2, y + h));
    points.add(CurvePoint(
      Offset(x + w - c2 + c2 * _kappa, y + h),
      Offset(x + w, y + h - c2 + c2 * _kappa),
      Offset(x + w, y + h - c2),
      NodeType.smooth,
    ));
  } else {
    points.add(Offset(x + w, y + h));
  }

  // Right edge → lower-right corner
  if (c3 > 0) {
    points.add(Offset(x + w, y + c3));
    points.add(CurvePoint(
      Offset(x + w, y + c3 - c3 * _kappa),
      Offset(x + w - c3 + c3 * _kappa, y),
      Offset(x + w - c3, y),
      NodeType.smooth,
    ));
  } else {
    points.add(Offset(x + w, y));
  }

  // Bottom edge → lower-left corner (back to start)
  if (c0 > 0) {
    points.add(Offset(x + c0, y));
    points.add(CurvePoint(
      Offset(x + c0 - c0 * _kappa, y),
      Offset(x, y + c0 - c0 * _kappa),
      Offset(x, y + c0),
      NodeType.smooth,
    ));
  } else {
    // Will close to start automatically.
  }

  return [
    VectorPath(start: start, points: points, closure: PathClosure.closed),
  ];
}

/// Generates circle/ellipse paths (unit circle centered at 0.5, 0.5).
List<VectorPath> _getCirclePaths(
    double angle1, double angle2, ArcType arcType) {
  // Full circle (angle1 == angle2 == 0)
  if (angle1 == 0 && angle2 == 0) {
    // Four quarter-circle arcs using cubic Bézier approximation.
    const cx = 0.5;
    const cy = 0.5;
    const r = 0.5;
    const k = r * _kappa;

    return [
      VectorPath(
        start: const Offset(cx + r, cy),
        points: [
          const CurvePoint(
            Offset(cx + r, cy + k),
            Offset(cx + k, cy + r),
            Offset(cx, cy + r),
            NodeType.smooth,
          ),
          const CurvePoint(
            Offset(cx - k, cy + r),
            Offset(cx - r, cy + k),
            Offset(cx - r, cy),
            NodeType.smooth,
          ),
          const CurvePoint(
            Offset(cx - r, cy - k),
            Offset(cx - k, cy - r),
            Offset(cx, cy - r),
            NodeType.smooth,
          ),
          const CurvePoint(
            Offset(cx + k, cy - r),
            Offset(cx + r, cy - k),
            Offset(cx + r, cy),
            NodeType.smooth,
          ),
        ],
        closure: PathClosure.closed,
      ),
    ];
  }

  // Arc / sector / chord
  const cx = 0.5;
  const cy = 0.5;
  const r = 0.5;

  // Generate arc points
  final points = <Object>[];
  final startAngle = angle1;
  var endAngle = angle2;
  if (endAngle <= startAngle) endAngle += 2 * math.pi;

  final startPt = Offset(
    cx + r * math.cos(startAngle),
    cy + r * math.sin(startAngle),
  );

  // Subdivide the arc into at most 90° segments
  var currentAngle = startAngle;
  while (currentAngle < endAngle) {
    var segEnd = currentAngle + math.pi / 2.0;
    if (segEnd > endAngle) segEnd = endAngle;
    final segSpan = segEnd - currentAngle;
    final alpha = 4.0 / 3.0 * math.tan(segSpan / 4.0);

    final p1 = Offset(
      cx + r * math.cos(currentAngle),
      cy + r * math.sin(currentAngle),
    );
    final p4 = Offset(
      cx + r * math.cos(segEnd),
      cy + r * math.sin(segEnd),
    );
    final p2 = Offset(
      p1.dx - alpha * r * math.sin(currentAngle),
      p1.dy + alpha * r * math.cos(currentAngle),
    );
    final p3 = Offset(
      p4.dx + alpha * r * math.sin(segEnd),
      p4.dy - alpha * r * math.cos(segEnd),
    );

    points.add(CurvePoint(p2, p3, p4, NodeType.smooth));
    currentAngle = segEnd;
  }

  // Handle closure based on arc type
  PathClosure closure;
  switch (arcType) {
    case ArcType.arc:
      closure = PathClosure.opened;
    case ArcType.chord:
      closure = PathClosure.closed;
    case ArcType.pieslice:
      points.add(const Offset(cx, cy));
      closure = PathClosure.closed;
  }

  return [
    VectorPath(start: startPt, points: points, closure: closure),
  ];
}

/// Generates polygon / star paths.
List<VectorPath> _getPolygonPaths(
    int cornersNum, double angle1, double angle2, double coef1, double coef2) {
  const cx = 0.5;
  const cy = 0.5;
  const r = 0.5;

  final points = <Object>[];
  final startAngle = math.pi / 2.0 + angle1;
  final step = 2.0 * math.pi / cornersNum;

  // First corner
  final startPt = Offset(
    cx + r * coef1 * math.cos(startAngle),
    cy + r * coef1 * math.sin(startAngle),
  );

  for (var i = 0; i < cornersNum; i++) {
    // Midpoint
    final midAngle = startAngle + step * i + step / 2.0 + angle2;
    points.add(Offset(
      cx + r * coef2 * math.cos(midAngle),
      cy + r * coef2 * math.sin(midAngle),
    ));

    // Next corner (skip first since it's the start point)
    if (i < cornersNum - 1) {
      final cornerAngle = startAngle + step * (i + 1) + angle1;
      points.add(Offset(
        cx + r * coef1 * math.cos(cornerAngle),
        cy + r * coef1 * math.sin(cornerAngle),
      ));
    }
  }

  return [
    VectorPath(start: startPt, points: points, closure: PathClosure.closed),
  ];
}
