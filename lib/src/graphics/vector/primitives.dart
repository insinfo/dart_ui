/// Artistic or paragraph text.
///
/// Text content is stored as a plain string in [textContent]. The [width]
/// field controls the text mode: -1 = artistic (single-line/free), positive
/// values define a text block width for paragraph mode.
class VectorText extends PrimitiveObject {
  VectorText({
    super.parent,
    super.trafo,
    super.style,
    super.fillTrafo,
    super.strokeTrafo,
    this.textContent = '',
    this.width = kTextBlockWidth,
    List<double>? initialTrafo,
    this.markup = const [],
  }) : initialTrafo = initialTrafo ?? List.of(kNormalTrafo);

  /// The text content.
  String textContent;

  /// Text block width (-1 = artistic mode).
  double width;

  /// Initial transform.
  List<double> initialTrafo;

  /// Rich-text markup segments.
  List<TextMarkup> markup;

  @override
  bool get isText => true;

  @override
  bool get isClosed => true;

  /// True if this is an artistic text (single-line, free placement).
  bool get isArtisticText => width == kTextBlockWidth;

  /// True if this is a paragraph text block.
  bool get isParagraphText => width > 0;

  @override
  List<VectorPath> getInitialPaths() {
    // Text path generation requires a font engine. Return an empty list
    // as a placeholder; the renderer handles text separately.
    return [];
  }

  /// The ink extent of this text, in the object's own units, measured by
  /// whoever owns the fonts.
  ///
  /// Installed by the vector editor (see `vector_editor/text_metrics.dart`),
  /// because this layer has no font engine and must not grow one: a document
  /// model that depended on a rasterizer could not be loaded, converted or
  /// serialized without one.
  ///
  /// Null falls back to [approximateInk], which is a plausible box rather than
  /// a correct one - good enough that a document opened headless still has
  /// selectable text, not good enough to place a caret with.
  static VectorTextInk Function(VectorText text)? inkProvider;

  /// The ink box of this text, measured or approximated.
  VectorTextInk get ink => inkProvider?.call(this) ?? approximateInk(this);

  /// A metrics-free estimate, for when no font engine has been installed.
  ///
  /// 0.52 em per character and the usual 0.8/0.2 split of the em box: those
  /// are the proportions of a Latin sans face, and they are only ever used to
  /// give the text *some* box rather than the zero-sized one that made text
  /// impossible to click at all.
  static VectorTextInk approximateInk(VectorText text) {
    final size = text.style.textStyle.fontSize;
    return VectorTextInk(
      width: text.textContent.length * size * 0.52,
      ascent: size * 0.8,
      descent: size * 0.2,
    );
  }

  /// The box the text occupies, transformed.
  ///
  /// Overridden because [PrimitiveObject.updateBbox] derives the box from
  /// `cachePaths`, and text has none - so every text object had
  /// `cacheBbox == Rect.zero` and could never be hit-tested, selected,
  /// double-clicked or enclosed by a rubber band. Nothing about the text was
  /// wrong on screen; it simply did not exist to the pointer.
  @override
  void updateBbox() {
    final metrics = ink;
    // The trafo's translation *is* the baseline origin - that is what the
    // renderer draws from - so the local box hangs off the origin: up by the
    // ascent, down by the descent, right by the advance.
    final corners = <Offset>[
      const Offset(0, 0),
      Offset(metrics.width, 0),
      Offset(0, -metrics.ascent),
      Offset(metrics.width, -metrics.ascent),
      Offset(0, metrics.descent),
      Offset(metrics.width, metrics.descent),
    ];
    var minX = double.infinity;
    var minY = double.infinity;
    var maxX = double.negativeInfinity;
    var maxY = double.negativeInfinity;
    for (final corner in corners) {
      final point = applyTrafoToPoint(corner, trafo);
      if (point.dx < minX) minX = point.dx;
      if (point.dy < minY) minY = point.dy;
      if (point.dx > maxX) maxX = point.dx;
      if (point.dy > maxY) maxY = point.dy;
    }
    cacheBbox = Rect.fromLTRB(minX, minY, maxX, maxY);
  }

  @override
  DocumentObject createEmpty() => VectorText();

  @override
  void copyFields(DocumentObject target) {
    super.copyFields(target);
    if (target is VectorText) {
      target.textContent = textContent;
      target.width = width;
      target.initialTrafo = List.of(initialTrafo);
      target.markup = markup.map((m) => m.copyWith()).toList();
    }
  }

  @override
  String toString() {
    final preview = textContent.length > 30
        ? '${textContent.substring(0, 30)}...'
        : textContent;
    return 'VectorText("$preview", ${isArtisticText ? "artistic" : "paragraph"})';
  }
}

/// A segment of rich-text markup applied to a range of the text.
class TextMarkup {
  const TextMarkup({
    this.startIndex = 0,
    this.endIndex = 0,
    this.fontFamily,
    this.fontSize,
    this.bold,
    this.italic,
    this.color,
  });

  final int startIndex;
  final int endIndex;
  final String? fontFamily;
  final double? fontSize;
  final bool? bold;
  final bool? italic;
  final int? color; // packed ARGB

  TextMarkup copyWith({
    int? startIndex,
    int? endIndex,
    String? fontFamily,
    double? fontSize,
    bool? bold,
    bool? italic,
    int? color,
  }) =>
      TextMarkup(
        startIndex: startIndex ?? this.startIndex,
        endIndex: endIndex ?? this.endIndex,
        fontFamily: fontFamily ?? this.fontFamily,
        fontSize: fontSize ?? this.fontSize,
        bold: bold ?? this.bold,
        italic: italic ?? this.italic,
        color: color ?? this.color,
      );
}

/// One line of text's ink extent, in the text object's own units.
final class VectorTextInk {
  const VectorTextInk({
    required this.width,
    required this.ascent,
    required this.descent,
  });

  /// The advance width of the whole string.
  final double width;

  /// How far the tallest glyph rises above the baseline.
  final double ascent;

  /// How far the deepest glyph falls below it.
  final double descent;

  double get height => ascent + descent;

  @override
  String toString() =>
      'VectorTextInk(width: $width, ascent: $ascent, descent: $descent)';
}

