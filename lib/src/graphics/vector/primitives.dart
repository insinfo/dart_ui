/// A circle or ellipse, possibly an arc or sector.
///
/// The initial shape is a unit circle centered at (0.5, 0.5). The [trafo]
/// maps it to the desired position, size, and aspect ratio.
class VectorCircle extends PrimitiveObject {
  VectorCircle({
    super.parent,
    super.trafo,
    super.style,
    super.fillTrafo,
    super.strokeTrafo,
    this.angle1 = 0.0,
    this.angle2 = 0.0,
    this.arcType = ArcType.chord,
    List<double>? initialTrafo,
  }) : initialTrafo = initialTrafo ?? List.of(kNormalTrafo);

  /// Start angle (radians) for arc/sector.
  double angle1;

  /// End angle (radians) for arc/sector.
  double angle2;

  /// Type of arc (chord, pie, open arc).
  ArcType arcType;

  /// Initial transform that maps the unit circle to the desired ellipse.
  List<double> initialTrafo;

  @override
  bool get isCircle => true;

  @override
  bool get isClosed => arcType != ArcType.arc;

  /// Creates from a bounding rect `[cx, cy, w, h]`.
  factory VectorCircle.fromRect(
    List<double> rect, {
    double angle1 = 0.0,
    double angle2 = 0.0,
    ArcType arcType = ArcType.chord,
    VectorStyle? style,
  }) {
    final trafo = [rect[2], 0.0, 0.0, rect[3], rect[0], rect[1]];
    return VectorCircle(
      trafo: trafo,
      initialTrafo: List.of(trafo),
      angle1: angle1,
      angle2: angle2,
      arcType: arcType,
      style: style,
    );
  }

  Offset get center => const Offset(0.5, 0.5);

  @override
  List<VectorPath> getInitialPaths() {
    return _getCirclePaths(angle1, angle2, arcType);
  }

  @override
  DocumentObject createEmpty() => VectorCircle();

  @override
  void copyFields(DocumentObject target) {
    super.copyFields(target);
    if (target is VectorCircle) {
      target.angle1 = angle1;
      target.angle2 = angle2;
      target.arcType = arcType;
      target.initialTrafo = List.of(initialTrafo);
    }
  }

  @override
  String toString() =>
      'VectorCircle(angle1=${angle1.toStringAsFixed(2)}, angle2=${angle2.toStringAsFixed(2)}, $arcType)';
}

