/// Largura em células da string fornecida.
int textWidth(String text) {
  var w = 0;
  for (final _ in text.toUpperCase().runes) {
    w += fontCellWidth;
  }
  if (w > 0) w -= 1; // último glifo não precisa do espaçamento à direita
  return w;
}

/// Desenha [text] centralizado horizontal e verticalmente dentro de [area]
/// no canvas dado. Apenas o subconjunto da tabela é suportado; caracteres
/// ausentes são desenhados como espaço.
void drawText(
  void Function(int x, int y) putPixel,
  String text,
  Rect area,
) {
  final upper = text.toUpperCase();
  final cells = upper.runes.toList();
  final w = textWidth(upper);
  const h = fontCellHeight;
  var originX = area.left + ((area.width - w) ~/ 2);
  var originY = area.top + ((area.height - h) ~/ 2);
  if (originX < area.left) originX = area.left;
  if (originY < area.top) originY = area.top;

  var cellX = originX;
  for (final rune in cells) {
    final glyph = _glyphs[String.fromCharCode(rune)];
    if (glyph != null) {
      for (var row = 0; row < fontGlyphHeight; row++) {
        final bits = glyph[row];
        final py = originY + row;
        for (var col = 0; col < fontGlyphWidth; col++) {
          if ((bits >> (4 - col)) & 1 == 1) {
            putPixel(cellX + col, py);
          }
        }
      }
    }
    cellX += fontCellWidth;
  }
}
